void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size) {
	HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_3);
	sayac++;
	lastPacketTime = HAL_GetTick();

	if (buffer[0] == 0xAA) {
		packetCRC = checkSumCalc(&buffer, Size - 2);

		if (packetCRC == buffer[Size - 2] && buffer[0] == 0xAA && buffer[Size - 1] == 0x0D){
			memcpy(&receivedData, buffer + 1, sizeof(SensorData));

		    packCSDatas();

		    HAL_UART_Transmit(&huart2, txGSBuffer, sizeof(txGSBuffer), HAL_MAX_DELAY);

			HAL_UARTEx_ReceiveToIdle_DMA(&huart1, buffer, 256);
			__HAL_DMA_DISABLE_IT(&hdma_usart1_rx, DMA_IT_HT);
		}
	}
}

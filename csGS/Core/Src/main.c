unsigned char checkSumCalc(void *data, size_t size){
    int checkSum = 0;

    uint8_t buffer[size];
    memcpy(buffer, data, size);

    for(int i = 0; i < size; i++){
    	checkSum += buffer[i];
    }

    return (unsigned char) (checkSum % 256);
}

